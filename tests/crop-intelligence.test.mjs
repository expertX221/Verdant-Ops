import assert from 'node:assert/strict';
import {createRequire} from 'node:module';
import {fileURLToPath} from 'node:url';
import {dirname,join} from 'node:path';
const require=createRequire(import.meta.url);
const {assess,cropForLabel,CROPS}=require(join(dirname(fileURLToPath(import.meta.url)),'..','crop-intelligence.js'));
const row=(label,score)=>({label,score});
assert.equal(cropForLabel('Tomato with Early Blight'),'Tomato');
assert.equal(cropForLabel('Healthy Bell Pepper Plant'),'Bell Pepper');
assert.equal(cropForLabel('Corn (Maize) with Common Rust'),'Corn');
assert.equal(cropForLabel('Cedar Apple Rust'),'Apple');
assert.equal(cropForLabel('Unknown Leaf'),'null'==='null'?null:'null');
assert(!CROPS.includes('Lettuce'));
const high=[row('Tomato with Early Blight',.83),row('Tomato with Late Blight',.06),row('Potato with Early Blight',.04),row('Apple Scab',.02)];
const auto=assess(high);
assert.equal(auto.crop,'Tomato');assert(auto.accepted);assert.equal(auto.top.label,'Tomato with Early Blight');
const supplied=assess(high,{selectedCrop:'Tomato'});
assert(supplied.accepted);assert(supplied.provided);assert.equal(supplied.conditions[0].crop,'Tomato');
const conflict=assess([row('Potato with Late Blight',.86),row('Tomato with Early Blight',.06),row('Tomato with Late Blight',.03)],{selectedCrop:'Tomato'});
assert(!conflict.accepted && conflict.conflict && /strongly resembles Potato/.test(conflict.reason));
const absent=assess(high,{selectedCrop:'Cucumber'});
assert(!absent.accepted && !absent.cropSupported && /not covered/.test(absent.reason));
const poor=assess(high,{qualityGood:false});assert(!poor.accepted && /Photo quality/.test(poor.reason));
const ambiguous=assess([row('Tomato with Early Blight',.47),row('Potato with Early Blight',.41),row('Tomato with Late Blight',.06)]);
assert(!ambiguous.accepted && ambiguous.crop==='Tomato');
const cropFirst=assess([row('Potato with Early Blight',.24),row('Tomato with Early Blight',.20),row('Tomato with Late Blight',.18),row('Tomato with Leaf Mold',.17)]);
assert.equal(cropFirst.crop,'Tomato','Multiple tomato disease classes provide evidence for tomato as a crop');
assert(!cropFirst.accepted,'Ambiguous low-score disease must not be called reliable');
assert.equal(assess([row('Unknown disease',.9)]).accepted,false);
const multi=assess([row('Bell Pepper with Bacterial Spot',.75),row('Tomato with Early Blight',.12)],{selectedCrop:'Pepper'});
assert.equal(multi.crop,'Bell Pepper');assert(multi.accepted);
console.log('PASS: crop-first grouping, confirmed selection, unsupported crops, conflict and uncertainty checks');
